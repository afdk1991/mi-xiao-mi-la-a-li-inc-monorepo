// 隐私合规：定位用途告知与同意状态持久化。
//
// 背景：本应用采集 GPS 实时位置（属敏感个人信息），合规要求在采集前明确告知用途并征得同意，
// 且需在应用内可随时查阅政策全文。因此首次开启定位时弹出告知，用户确认后才真正调用定位。
// 同意状态记在本地（与设置同源的 localStorage），换设备或清缓存后会重新征求同意。

const ACK_KEY = 'delivery.privacyAcked'

/** 用户是否已确认过定位用途告知 */
export function privacyAcked(): boolean {
  try {
    return localStorage.getItem(ACK_KEY) === '1'
  } catch {
    // 隐私模式下 localStorage 可能不可用，此时不阻断功能，但每次都会重新征求同意
    return false
  }
}

/** 记录用户已确认 */
export function ackPrivacy(): void {
  try {
    localStorage.setItem(ACK_KEY, '1')
  } catch {
    /* ignore */
  }
}

/** 重置确认状态（供「设置」中重新查看/撤回同意使用） */
export function resetPrivacyAck(): void {
  try {
    localStorage.removeItem(ACK_KEY)
  } catch {
    /* ignore */
  }
}

